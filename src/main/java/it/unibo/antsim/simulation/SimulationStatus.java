/**
 * The enum Simulation status.
 */
public enum SimulationStatus {
    /**
     * Idle simulation status.
     */
    IDLE,

    /**
     * Running simulation status.
     */
    RUNNING,

    /**
     * Paused simulation status.
     */
    PAUSED,

    /**
     * Stopped simulation status.
     */
    STOPPED
}
